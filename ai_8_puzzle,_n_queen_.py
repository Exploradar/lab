def water_jug_problem(jug1_capacity, jug2_capacity, target):
    """
    Solves the water jug problem using BFS.

    Args:
        jug1_capacity: Capacity of the first jug.
        jug2_capacity: Capacity of the second jug.
        target: The target amount of water to achieve.

    Returns:
        A list of tuples representing the steps to reach the target, or None if no solution exists.
    """

    visited = set()
    queue = [(0, 0, [])]  # (jug1_level, jug2_level, path)

    while queue:
        jug1_level, jug2_level, path = queue.pop(0)

        if jug1_level == target or jug2_level == target:
            return path + [(jug1_level, jug2_level)]

        if (jug1_level, jug2_level) in visited:
            continue
        visited.add((jug1_level, jug2_level))

        print(f"Current state: Jug 1 = {jug1_level}, Jug 2 = {jug2_level}")

        # Possible actions:
        # 1. Fill jug1
        queue.append((jug1_capacity, jug2_level, path + [(jug1_level, jug2_level)]))
        # 2. Fill jug2
        queue.append((jug1_level, jug2_capacity, path + [(jug1_level, jug2_level)]))
        # 3. Empty jug1
        queue.append((0, jug2_level, path + [(jug1_level, jug2_level)]))
        # 4. Empty jug2
        queue.append((jug1_level, 0, path + [(jug1_level, jug2_level)]))
        # 5. Pour water from jug1 to jug2
        pour_amount = min(jug1_level, jug2_capacity - jug2_level)
        queue.append((jug1_level - pour_amount, jug2_level + pour_amount, path + [(jug1_level, jug2_level)]))
        # 6. Pour water from jug2 to jug1
        pour_amount = min(jug2_level, jug1_capacity - jug1_level)
        queue.append((jug1_level + pour_amount, jug2_level - pour_amount, path + [(jug1_level, jug2_level)]))

    return None  # No solution


