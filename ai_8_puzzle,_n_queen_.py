import heapq

def uniform_cost_search(graph, start, goal):
    """
    Performs Uniform Cost Search on a graph.

    Args:
        graph: A dictionary representing the graph where keys are nodes and values are dictionaries of neighbors with associated costs.
        start: The starting node.
        goal: The goal node.

    Returns:
        A tuple containing:
            - A list of nodes representing the shortest path from the start to the goal.
            - The total cost of the path.
        Returns (None, infinity) if no path is found.
    """
    priority_queue = [(0, start, [start])]  # (cost, node, path)
    visited = set()

    while priority_queue:
        cost, current_node, path = heapq.heappop(priority_queue)

        if current_node == goal:
            return path, cost

        if current_node in visited:
            continue

        visited.add(current_node)

        for neighbor, neighbor_cost in graph[current_node].items():
            if neighbor not in visited:
                heapq.heappush(priority_queue, (cost + neighbor_cost, neighbor, path + [neighbor]))

    return None, float('inf')  # No path found


